/**
 * Nested directives inside repeat() rows (workstream RW, H-18 option (b)): everything a component-level
 * list or branch can contain also works inside a row, at any depth.
 *
 * - RW-6: a row collects only its own directives. A whenElse() or repeat() inside the row's when() /
 *   whenElse() content, or inside a nested list's rows, belongs to that directive, exactly as at
 *   component level (P20's double collection).
 * - RW-2: a row's when() / whenElse() content is bound by the branch initializer, like a component-level
 *   branch: events, child components, nested directives and lists, and the Signal<Signal<T>[]> pattern.
 *   A branch pre-rendered in the row is its own template there.
 * - RW-3: a list inside a row is generated by emitRepeat, like any other list: events, batch rows, empty
 *   template, index refresh, child components, and an inner item that shadows the outer one.
 *
 * The analysis cases call the template processor directly; the build cases compile an app with the
 * real pipeline (development build, templates as written).
 */
import { describe, expect, test } from 'bun:test';
import ts from 'typescript';
import { processHtmlTemplateWithConditionals } from './template-processing.js';
import { buildAndReadJs } from '../../testing/build-project.js';

const DEV = { config: { strictTypeCheck: false } };

/** The emitted row template of list `id` (`__tpl_<id> = __T(\`…\`)`). */
const rowTemplate = (js: string, id: string): string | undefined =>
  new RegExp(`\\b__tpl_${id} = __T\\(\`([^\`]*)\`\\)`).exec(js)?.[1];

/** The analysis of a component template whose only list is `row` over `rows()`, keyed by id. */
const analyseRow = (row: string, initializers: [string, boolean][] = [['show', true]]) => {
  const result = processHtmlTemplateWithConditionals(
    '<ul>${repeat(rows(), (r) => html`' + row + '`, null, (r) => r.id)}</ul>',
    new Map(initializers),
    0,
  );
  expect(result.repeatBlocks).toHaveLength(1);
  return result.repeatBlocks[0]!;
};

describe('RW-6 a row collects only its own directives', () => {
  test('a repeat() inside a row when() belongs to the when() (P20)', () => {
    const rep = analyseRow(
      '<li><div class="w" ${when(show())}><ol>${repeat(r.tags, (t) => html`<li>${t}</li>`)}</ol></div></li>',
    );
    expect(rep.nestedRepeats).toHaveLength(0);
    expect(rep.nestedConditionals).toHaveLength(1);
    expect(rep.nestedConditionals[0]!.nestedRepeats).toHaveLength(1);
    // The row template is whole: the when() is pre-rendered between its anchors, the list's anchor in it
    expect(rep.itemTemplate).toMatch(
      /^<li><!--b\d+\(--><div class="w"><ol><!--b\d+\.--><\/ol><\/div><!--b\d+\)--><\/li>$/,
    );
  });

  test('a whenElse() inside a row when() belongs to the when()', () => {
    const rep = analyseRow(
      '<li><div ${when(show())}>${whenElse(r.on, html`<b>y</b>`, html`<i>n</i>`)}</div><s>${r.name}</s></li>',
    );
    expect(rep.nestedWhenElse).toHaveLength(0);
    expect(rep.nestedConditionals[0]!.nestedWhenElse).toHaveLength(1);
    expect(rep.itemTemplate).toMatch(/<\/div><!--b\d+\)--><s data-thane-ref="i\d+">\$\{r\.name\}<\/s><\/li>$/);
  });

  test('a repeat() inside a row whenElse() branch belongs to the branch', () => {
    const rep = analyseRow(
      '<li>${whenElse(r.on, html`<ol>${repeat(r.tags, (t) => html`<li>${t}</li>`)}</ol>`, html`<i>n</i>`)}</li>',
    );
    expect(rep.nestedRepeats).toHaveLength(0);
    expect(rep.nestedWhenElse).toHaveLength(1);
    expect(rep.nestedWhenElse[0]!.thenRepeats).toHaveLength(1);
    expect(rep.itemTemplate).toMatch(/^<li><!--b\d+\(--><!--b\d+\|--><!--b\d+\)--><\/li>$/);
  });

  test('a whenElse() inside a row whenElse() branch belongs to the branch', () => {
    const rep = analyseRow(
      '<li>${whenElse(r.on, html`<p>${whenElse(r.x, html`<b>1</b>`, html`<b>2</b>`)}</p>`, html`<i>n</i>`)}</li>',
    );
    expect(rep.nestedWhenElse).toHaveLength(1);
    expect(rep.nestedWhenElse[0]!.thenWhenElse).toHaveLength(1);
  });

  test("a whenElse() inside a nested list's rows belongs to that list", () => {
    const rep = analyseRow(
      '<li><ol>${repeat(r.tags, (t) => html`<li>${whenElse(t.on, html`<b>y</b>`, html`<i>n</i>`)}</li>`)}</ol></li>',
    );
    expect(rep.nestedWhenElse).toHaveLength(0);
    expect(rep.nestedRepeats).toHaveLength(1);
    expect(rep.nestedRepeats[0]!.nestedWhenElse).toHaveLength(1);
    expect(rep.itemTemplate).toMatch(/^<li><ol><!--b\d+\.--><\/ol><\/li>$/);
  });

  test("a repeat() inside a nested list's rows belongs to that list", () => {
    const rep = analyseRow(
      '<li><ol>${repeat(r.tags, (t) => html`<li><i>${repeat(t.subs, (s) => html`<u>${s}</u>`)}</i></li>`)}</ol></li>',
    );
    expect(rep.nestedRepeats).toHaveLength(1);
    expect(rep.nestedRepeats[0]!.nestedRepeats).toHaveLength(1);
    expect(rep.itemTemplate).toMatch(/^<li><ol><!--b\d+\.--><\/ol><\/li>$/);
  });

  test('the emitted row template of P20 is whole', async () => {
    const js = await buildAndReadJs(
      `
import { defineComponent, signal, mount } from 'thane';
export const App = defineComponent('test-app', () => {
  const rows = signal([{ id: 1, tags: ['t1', 't2'] }]);
  const show = signal(true);
  return {
    template: html\`<ul>\${repeat(rows(), (r) => html\`<li><div class="w" \${when(show())}><ol>\${repeat(r.tags, (t) => html\`<li class="tag">\${t}</li>\`)}</ol></div></li>\`, null, (r) => r.id)}</ul>\`,
  };
});
mount(App);
`,
      DEV,
    );
    expect(rowTemplate(js, 'b0')).toBe('<li><!----><div class="w"><ol><!----></ol></div><!----></li>');
  });
});

// ── RW-2: row directives use the branch initializer ──

/** A child component in its own file (one component per file, THANE407), with a name no other fixture uses. */
const KID = [
  "import { defineComponent } from 'thane';",
  "export const RwNestKid = defineComponent<{ label: string }>('rw-nest-kid', ({ props }) => ({ template: html`<em>${props.label}</em>` }));",
].join('\n');

/**
 * Builds a component whose template is `template` (written as in the source), with row data and RwNestKid.
 * A development build returns the compiled component files only, without the runtime.
 */
const buildRows = (template: string, mode: 'dev' | 'prod' = 'dev'): Promise<string> =>
  buildAndReadJs(
    [
      "import { defineComponent, signal, mount } from 'thane';",
      "import { RwNestKid } from './kid.js';",
      "export const App = defineComponent('test-app', () => {",
      "  const rows = signal([{ id: 1, first: 'John', last: 'Doe', on: true, tags: ['a'] }]);",
      "  const sigRows = signal([signal({ id: 1, on: true, name: 's1' })]);",
      '  const show = signal(true);',
      '  const bump = (x) => x;',
      `  return { template: html\`${template}\` };`,
      '});',
      'mount({ component: App, target: document.body });',
    ].join('\n'),
    { config: { ...DEV.config, isProd: mode === 'prod' }, extraFiles: { 'src/kid.ts': KID } },
  ).then((js) => (mode === 'dev' ? js.slice(js.indexOf('// .tmp-thane')) : js));

/** The bundle's string and template literals, cooked (a production bundle prints templates as strings). */
const literals = (js: string): string[] => {
  const out: string[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) out.push(node.text);
    ts.forEachChild(node, visit);
  };
  visit(ts.createSourceFile('bundle.js', js, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS));
  return out;
};

/** A row list over `rows()` keyed by id, with row template `row`. */
const list = (row: string): string => '<ul>${repeat(rows(), (r) => html`' + row + '`, null, (r) => r.id)}</ul>';

describe('RW-2 row directives use the branch initializer', () => {
  for (const mode of ['dev', 'prod'] as const) {
    test(`a when() pre-rendered in a row is its own template there: two bindings with a space (${mode})`, async () => {
      const js = await buildRows(
        list('<li><span ${when(show())} title=${r.first}>${r.first} ${r.last}</span></li>'),
        mode,
      );
      const all = literals(js);
      const row = all.find((l) => l.startsWith('<li><!---->') && l.endsWith('<!----></li>'));
      expect(row).toBeDefined();
      // The when()'s own template, which its initializer's paths are computed on, is what the row holds
      const content = row!.slice('<li><!---->'.length, -'<!----></li>'.length);
      expect(content).toMatch(/^<span[^>]*><!----> <!----> <!----> <!----><\/span>$/);
      expect(all.filter((l) => l === content)).toHaveLength(1);
    });
  }

  test('handlers in both whenElse() branches of a row are bound by the branch initializers (P4)', async () => {
    const js = await buildRows(
      list(
        '<li>${whenElse(r.on, html`<button @click=${() => bump(r.id)}>t</button>`, html`<button @click.stop=${() => bump(-r.id)}>e</button>`)}</li>',
      ),
    );
    expect(js).toMatch(/\.addEventListener\("click", \(\) => bump\(r\$\(\)\.id\)\);/);
    expect(js).toMatch(
      /\.addEventListener\("click", \(e\) => \{\s*e\.stopPropagation\(\);\s*\(\(\) => bump\(-r\$\(\)\.id\)\)\(e\);/,
    );
  });

  test('a shorthand property that names the item keeps its key in a row branch', async () => {
    const js = await buildRows(
      list('<li>${whenElse(r.on, html`<button @click=${() => bump({ r })}>t</button>`, html`<i>n</i>`)}</li>'),
    );
    expect(js).toMatch(/\.addEventListener\("click", \(\) => bump\(\{ r: r\$\(\) \}\)\);/);
  });

  test('a child component in a pre-rendered row when() is mounted by its initializer (P7)', async () => {
    const js = await buildRows(list('<li><div ${when(show())}>${RwNestKid({ label: r.first })}</div></li>'));
    expect(js).toMatch(/__dc\(RwNestKid\.__f\(\w+, \{ label: r\.first \}\)\)/);
    // The props read the item variable itself: the row factory's parameter has its name
    expect(js).toMatch(/\(r, _idx, _ref\) =>/);
  });

  test('a child component in a row when() on the item builds and is mounted by its initializer', async () => {
    const js = await buildRows(list('<li><div ${when(r.on)}>${RwNestKid({ label: r.first })}</div></li>'));
    expect(js).toMatch(
      /__bindIfExpr\(\w+, \w+, \[r\$\], \(\) => r\$\(\)\.on, `[^`]*`, \(_c\) => \{[^}]*__dc\(RwNestKid\.__f\(/,
    );
  });

  test("child components in a row's whenElse() branches build and are mounted by their initializers", async () => {
    const js = await buildRows(
      list(
        '<li>${whenElse(r.on, html`<p>${RwNestKid({ label: "t" + r.first })}</p>`, html`<p>${RwNestKid({ label: "e" + r.first })}</p>`)}</li>',
      ),
    );
    expect(js.match(/__dc\(RwNestKid\.__f\(/g)).toHaveLength(2);
  });

  test('a whenElse() and a list inside a row when() are bound by its initializer (P20)', async () => {
    const js = await buildRows(
      list(
        '<li><div ${when(show())}>${whenElse(r.on, html`<b>${r.first}</b>`, html`<i>off</i>`)}<ol>${repeat(r.tags, (t) => html`<li>${t}</li>`)}</ol></div></li>',
      ),
    );
    // The row's list and the one inside its when()
    expect(js.match(/createKeyedReconciler\(/g)).toHaveLength(2);
    expect(js).toMatch(
      /__bindIf\(\w+, \w+, show, `[^`]*`, \(_c\) => \{[\s\S]*createKeyedReconciler\([\s\S]*__bindIfExpr\(/,
    );
  });

  test('rows whose items are signals: the directives read the item variable, the row factory parameter', async () => {
    const js = await buildRows(
      '<ul>${repeat(sigRows(), (row) => html`<li><b ${when(row().on)}>${row().name}</b></li>`, null, (row) => row().id)}</ul>',
    );
    expect(js).toMatch(/\(row, _idx, _ref\) =>/);
    expect(js).toMatch(/__bindIfExpr\(\w+, \w+, \[row\], \(\) => row\(\)\.on,/);
    expect(js).toMatch(/row\.subscribe\(/);
  });

  test('a row whose directives read the item only through its row signal declares no item alias', async () => {
    const js = await buildRows(list('<li><span ${when(r.on)}>${r.first}</span></li>'));
    expect(js).not.toMatch(/const r = item/);
    expect(js).not.toMatch(/_nsubs/);
  });
});

// ── RW-3: lists inside rows are generated by emitRepeat ──

/** A row list over `rows()` whose row holds a list over `r.tags` with row template `inner`. */
const nested = (inner: string, extra = ''): string =>
  list('<li><ol>${repeat(r.tags, ' + inner + extra + ')}</ol></li>');

describe('RW-3 lists inside rows are generated by emitRepeat', () => {
  test('an inner list has its own reconciler, delegated listener and batch rows, like any list (P2)', async () => {
    const js = await buildRows(nested('(t) => html`<li><button @click=${() => bump(t)}>${t}</button></li>`'));
    expect(js).not.toMatch(/_nr(?:El|Rc|C|Tc|Item)_?/);
    // The inner rows need no cleanups: batch rows with a shared update, as at component level
    expect(js).toMatch(/const _bind_b\d+ = \(_el2?, t, _idx2?\) => \{/);
    expect(js).toMatch(/__batchRows\(16, _tc_b\d+, _bind_b\d+, _update_b\d+\)/);
    // The inner container's own listener, inside the outer row factory
    expect(js).toMatch(/_ct_b\d+\.addEventListener\("click", \(e\) => \{[^}]*_row\.parentNode !== _ct_b\d+/);
    // The inner list's subscription and clear go into the outer row's cleanups
    expect(js).toMatch(/_cleanups\.push\(\(\) => _rc_b\d+\.clearAll\(\)\);/);
  });

  test("an inner list's empty template and index bindings are kept (reorder refresh)", async () => {
    const js = await buildRows(
      nested('(t, j) => html`<li>${j}:${t}</li>`', ', html`<li class="none">none</li>`, (t) => t'),
    );
    expect(js).toMatch(/const _syncEmpty_b\d+ = \(items\) => \{/);
    // trackIndex: the reconciler refreshes rows that move
    expect(js).toMatch(/__batchRows\(16, _tc_b\d+, _bind_b\d+, _update_b\d+\),\s*true\s*\)/);
  });

  test('a child component in an inner row is mounted by the inner row factory, its props reading the outer row', async () => {
    const js = await buildRows(nested('(t) => html`<li>${RwNestKid({ label: r.first + t })}</li>`'));
    expect(js).toMatch(/__dc\(RwNestKid\.__f\(\w+, \{ label: r\.first \+ t \}\)\)/);
  });

  test("an inner list whose item has the outer item's name reads its own item", async () => {
    const js = await buildRows(nested('(r) => html`<li>${r}</li>`'));
    // The inner rows write their own item; the outer row signal is only the list's source
    expect(js).toMatch(/_e0\.textContent = \(_p0 = r2?\) \?\? ""/);
    expect(js).toMatch(/const _items_b\d+ = \(\) => r\$\(\)\.tags;/);
  });

  test('an element after an inner list in its container is captured for the outer row delegated listener', async () => {
    const js = await buildRows(
      list('<li><ol>${repeat(r.tags, (t) => html`<li>${t}</li>`)}<li @click=${() => bump(r.id)}>after</li></ol></li>'),
    );
    expect(js).toMatch(/_el\.__e0 = _el\.firstElementChild\.firstElementChild;/);
    expect(js).toMatch(/if \(_row\.__e0\.contains\(e\.target\)\)/);
  });
});

describe('RW-3 an outer row item named item', () => {
  // Row factories named every row's item `item`, so a child's props that read an outer item written
  // `item` took the inner row's item (`item2.first + item2`). They keep the source's names now.
  test('a child in an inner row reads an outer item named item', async () => {
    const js = await buildRows(
      '<ul>${repeat(rows(), (item) => html`<li><ol>${repeat(item.tags, (t) => html`<li>${RwNestKid({ label: item.first + t })}</li>`)}</ol></li>`, null, (item) => item.id)}</ul>',
    );
    expect(js).not.toMatch(/_item_b\d+/);
    expect(js).toMatch(/__dc\(RwNestKid\.__f\(\w+, \{ label: item\.first \+ t \}\)\)/);
  });

  test('a row whose own item is named item reads it as item, with no alias', async () => {
    const js = await buildRows(
      '<ul>${repeat(rows(), (item) => html`<li><b ${when(show())}>${RwNestKid({ label: item.first })}</b></li>`, null, (item) => item.id)}</ul>',
    );
    expect(js).not.toMatch(/_item_b\d+/);
    expect(js).toMatch(/__dc\(RwNestKid\.__f\(\w+, \{ label: item\.first \}\)\)/);
  });
});
